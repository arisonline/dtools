/* =========================================
   GENERATE FAQ
========================================= */

function renderFaq(faqs) {

  const faqWrapper =
    document.getElementById("faq-wrapper");


  if (!faqWrapper) {

    console.warn(
      "FAQ wrapper not found."
    );

    return;

  }


  /*
     No FAQ data
  */

  if (!faqs || !faqs.length) {

    faqWrapper.innerHTML = "";

    return;

  }


  /*
     Generate FAQ cards
  */

  faqWrapper.innerHTML =
    faqs.map((faq, index) => {

      return `

        <div class="faq-card ${index === 0 ? "active" : ""}">

          <button
            type="button"
            class="faq-question"
          >

            <div class="faq-icon">

              ${getFaqIcon()}

            </div>

            <span>
              ${faq.question}
            </span>

            <div class="faq-arrow">

              ${getFaqArrow()}

            </div>

          </button>


          <div class="faq-answer">

            <p>
              ${faq.answer}
            </p>

          </div>

        </div>

      `;

    }).join("");


  /*
     Start accordion
  */

  initFaq();

}



/* =========================================
   FAQ ACCORDION
========================================= */

function initFaq() {

  const faqCards =
    document.querySelectorAll(".faq-card");


  faqCards.forEach(card => {

    const question =
      card.querySelector(".faq-question");


    if (!question) return;


    question.addEventListener(
      "click",
      () => {

        const isActive =
          card.classList.contains("active");


        /*
           Close all FAQ cards
        */

        faqCards.forEach(item => {

          item.classList.remove("active");

        });


        /*
           Open clicked card
        */

        if (!isActive) {

          card.classList.add("active");

        }

      }
    );

  });

}







/* =========================================
   GENERATE POPULAR TOOLS
========================================= */

function renderPopularTools() {

  const popularLinks =
    document.getElementById("popular-tools-links");


  if (!popularLinks) {

    console.warn(
      "Popular tools container not found."
    );

    return;

  }


  /*
     GitHub Pages project site:

     https://arisonline.github.io/dtools/

     Custom domain:

     https://dtools.dozni.com/
  */

  const siteBase =
    window.location.hostname.includes("github.io")
      ? "/dtools/"
      : "/";


  const popularTools =
    toolsData.filter(tool => tool.popular);


  popularLinks.innerHTML =
    popularTools.map(tool => {

      const toolURL =
        siteBase +
        tool.url.replace(/^\/+/, "");


      return `
        <a href="${toolURL}">
          ${tool.name}
        </a>
      `;

    }).join("");

}






/* =========================================
   GENERATE TOOL CONTENT
========================================= */

function renderToolContent(content) {

  const title =
    document.getElementById("tool-page-title");


  const description =
    document.getElementById("tool-page-description");


  const categories =
    document.getElementById("tool-page-categories");


  const howToTitle =
    document.getElementById("tool-howto-title");


  const howToList =
    document.getElementById("tool-guide-list");


  const credits =
    document.getElementById("tool-credits");


  const toolContent =
    document.getElementById("tool-content");


  if (!content) {

    console.warn(
      "No tool content supplied."
    );

    return;

  }


  /* =======================================
     TITLE
  ======================================= */

  if (title) {

    title.textContent =
      content.name || "";

  }


  /* =======================================
     DESCRIPTION
  ======================================= */

  if (description) {

    description.textContent =
      content.description || "";

  }


  /* =======================================
     CATEGORIES
  ======================================= */

  if (categories) {

    const categoryList =
      content.categories || [];


    if (!categoryList.length) {

      categories.innerHTML = "";

    } else {

      categories.innerHTML = `
        <span>Categories →</span>

        ${

          categoryList
            .map((category, index) => {

              return `
                <a
                  href="${category.url || "#"}"
                >
                  ${category.name}
                </a>

                ${
                  index <
                  categoryList.length - 1
                    ? ", "
                    : ""
                }
              `;

            })
            .join("")

        }
      `;

    }

  }


  /* =======================================
     HOW TO TITLE
  ======================================= */

  if (howToTitle) {

    howToTitle.textContent =
      content.howToTitle ||
      "How to Use This Tool?";

  }


  /* =======================================
     HOW TO LIST
  ======================================= */

  if (howToList) {

    const howTo =
      content.howTo || [];


    howToList.innerHTML =
      howTo.map(item => {

        return `
          <li>
            ${item}
          </li>
        `;

      }).join("");

  }


  /* =======================================
     CREDITS
  ======================================= */

  if (credits) {

    const creditList =
      content.credits || [];


    credits.innerHTML =
      creditList.map(credit => {

        return `
          <div class="credit-item">

            <a
              href="${credit.url || "#"}"
            >
              ${credit.name}
            </a>

            <span>
              ${credit.description || ""}
            </span>

          </div>
        `;

      }).join("");

  }


  /* =======================================
     LONG TOOL CONTENT
  ======================================= */

  if (toolContent) {

    toolContent.innerHTML =
      content.content || "";

  }


  /* =======================================
     POPULAR TOOLS
  ======================================= */

  renderPopularTools();

}





/* =========================================
   INITIALIZE TOOLS
========================================= */

function initTools() {

  console.log(
    "tools.js initialized"
  );


  const currentTool =
    getCurrentTool();


  if (currentTool) {

    console.log(
      "Current tool:",
      currentTool.name
    );


    renderToolContent(
      currentTool
    );


    renderFaq(
      currentTool.faqs || []
    );


    return;

  }


  console.log(
    "No specific tool detected."
  );


  renderToolContent(
    homeToolContent
  );


  renderFaq(
    homeFaqs
  );

}
